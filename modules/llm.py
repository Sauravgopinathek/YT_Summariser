"""NVIDIA NIM / LLM API client module.

Provides a clean, reusable interface for communicating with NVIDIA NIM
OpenAI-compatible inference endpoints with secure credential management,
diagnostics logging, and resilient error handling.
"""

import logging
import os
from typing import Optional

from openai import (
    APIConnectionError,
    APIStatusError,
    APITimeoutError,
    AuthenticationError,
    OpenAI,
    RateLimitError,
)

from config.settings import (
    DEFAULT_MAX_TOKENS,
    DEFAULT_TEMPERATURE,
    LLM_MAX_RETRIES,
    LLM_TIMEOUT_SECONDS,
    NVIDIA_BASE_URL,
    NVIDIA_MODEL,
    get_nvidia_api_key,
)

logger = logging.getLogger(__name__)


from modules.exceptions import (
    EmptyLLMResponseError,
    LLMAPIError,
    LLMAuthenticationError,
    LLMConfigurationError,
    LLMConnectionError,
    LLMContextOverflowError,
    LLMError,
    LLMRateLimitError,
    LLMTimeoutError,
    sanitize_secrets,
)


class NVIDIAClient:
    """Client for NVIDIA NIM LLM inference endpoints."""

    def __init__(
        self,
        api_key: Optional[str] = None,
        base_url: Optional[str] = None,
        model: Optional[str] = None,
        timeout: Optional[float] = None,
        max_retries: Optional[int] = None,
    ):
        """Initialize NVIDIA NIM client.

        Args:
            api_key: NVIDIA API key. If omitted, fetched securely from environment.
            base_url: NIM endpoint base URL.
            model: Model name/identifier.
            timeout: Request timeout in seconds.
            max_retries: Maximum number of internal retry attempts for transient errors.
        """
        self.api_key = api_key or get_nvidia_api_key()
        self.base_url = base_url or os.getenv("NVIDIA_BASE_URL", NVIDIA_BASE_URL)
        self.model = model or os.getenv("NVIDIA_MODEL", NVIDIA_MODEL)
        self.timeout = timeout if timeout is not None else LLM_TIMEOUT_SECONDS
        self.max_retries = max_retries if max_retries is not None else LLM_MAX_RETRIES

        if not self.api_key:
            logger.warning("NVIDIAClient initialized without an API key.")

        self._client: Optional[OpenAI] = None

    def _get_client(self) -> OpenAI:
        """Lazy-initialize and return the underlying OpenAI-compatible client."""
        if not self.api_key:
            self.api_key = get_nvidia_api_key()

        if not self.api_key:
            raise LLMConfigurationError(
                "NVIDIA API Key not found. Please set NVIDIA_API_KEY in your .env file."
            )

        if self._client is None:
            # Mask API key for diagnostics (e.g. nvapi-abc...1234)
            masked_key = (
                f"{self.api_key[:8]}...{self.api_key[-4:]}"
                if len(self.api_key) > 12
                else "***"
            )
            logger.info(
                "Initializing NVIDIA NIM client for model '%s' at '%s' with key [%s]",
                self.model,
                self.base_url,
                masked_key,
            )
            self._client = OpenAI(
                api_key=self.api_key,
                base_url=self.base_url,
                timeout=self.timeout,
                max_retries=self.max_retries,
            )
        return self._client

    def generate(
        self,
        system_prompt: str,
        user_prompt: str,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> str:
        """Execute chat completion request against the NVIDIA NIM endpoint.

        Args:
            system_prompt: Guiding system persona/instructions.
            user_prompt: User input or content to process.
            temperature: Sampling temperature (0.0 to 1.0).
            max_tokens: Maximum tokens in generated completion.

        Returns:
            The raw text content generated by the model.

        Raises:
            LLMConfigurationError: If API credentials are not set.
            LLMAuthenticationError: If API key is rejected by the server.
            LLMRateLimitError: If API quota or rate limits are reached.
            LLMTimeoutError: If the request exceeds timeout threshold.
            LLMConnectionError: If network connection drops or fails.
            LLMAPIError: For other API status failures.
        """
        client = self._get_client()

        temp = temperature if temperature is not None else DEFAULT_TEMPERATURE
        tokens = max_tokens if max_tokens is not None else DEFAULT_MAX_TOKENS

        messages = [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt},
        ]

        logger.info(
            "Sending inference request to NVIDIA NIM (model=%s, temp=%.2f, max_tokens=%d)",
            self.model,
            temp,
            tokens,
        )

        try:
            response = client.chat.completions.create(
                model=self.model,
                messages=messages,
                temperature=temp,
                max_tokens=tokens,
            )

            if not response.choices:
                raise EmptyLLMResponseError("NVIDIA NIM response contained no choices.")

            content = response.choices[0].message.content or ""
            if not content.strip():
                raise EmptyLLMResponseError("NVIDIA NIM returned a blank response with no text content.")

            logger.info("Successfully received %d characters from NVIDIA NIM", len(content))
            return content.strip()

        except AuthenticationError as e:
            logger.error("Authentication failed with NVIDIA NIM: %s", sanitize_secrets(e))
            raise LLMAuthenticationError(
                "NVIDIA API Key rejected (401 Unauthorized). Please verify your NVIDIA_API_KEY in .env."
            ) from e

        except RateLimitError as e:
            logger.warning("Rate limit exceeded for NVIDIA NIM: %s", sanitize_secrets(e))
            raise LLMRateLimitError(
                "NVIDIA NIM Rate Limit or Quota exceeded (429). Please wait before trying again."
            ) from e

        except APITimeoutError as e:
            logger.error("Request timed out after %.1f seconds: %s", self.timeout, sanitize_secrets(e))
            raise LLMTimeoutError(
                f"NVIDIA NIM request timed out after {self.timeout}s. Check network connection or increase timeout."
            ) from e

        except APIConnectionError as e:
            logger.error("Network connection error to %s: %s", self.base_url, sanitize_secrets(e))
            raise LLMConnectionError(
                f"Could not connect to NVIDIA NIM endpoint at {self.base_url}: {sanitize_secrets(e)}"
            ) from e

        except APIStatusError as e:
            clean_msg = sanitize_secrets(e.message)
            logger.error("NVIDIA NIM returned HTTP error status %s: %s", e.status_code, clean_msg)
            if e.status_code == 400 and ("context" in clean_msg.lower() or "token" in clean_msg.lower()):
                raise LLMContextOverflowError(
                    f"Model context limit exceeded ({e.status_code}): {clean_msg}"
                ) from e
            raise LLMAPIError(f"NVIDIA NIM API error ({e.status_code}): {clean_msg}") from e

        except Exception as e:
            if isinstance(e, LLMError):
                raise
            clean_msg = sanitize_secrets(e)
            logger.exception("Unexpected error during NVIDIA NIM inference")
            raise LLMAPIError(f"Unexpected error during LLM generation: {clean_msg}") from e

    def test_connection(self) -> str:
        """Execute a minimal handshake verification with the model.

        Sends a minimal prompt to verify credentials and endpoint reachability.

        Returns:
            The model's reply (expected to contain 'CONNECTION_SUCCESS').
        """
        system_prompt = "You are a connectivity test assistant. Follow instructions strictly."
        user_prompt = "Respond with exactly: CONNECTION_SUCCESS"
        response = self.generate(
            system_prompt=system_prompt,
            user_prompt=user_prompt,
            temperature=0.0,
            max_tokens=20,
        )
        return response


def verify_nvidia_connection(client: Optional[NVIDIAClient] = None) -> bool:
    """Convenience helper to test the NVIDIA NIM connection.

    Args:
        client: Optional NVIDIAClient instance.

    Returns:
        True if the handshake succeeded, False otherwise.
    """
    c = client or NVIDIAClient()
    try:
        reply = c.test_connection()
        return "CONNECTION_SUCCESS" in reply.upper()
    except Exception as e:
        logger.error("Connection check failed: %s", e)
        return False

